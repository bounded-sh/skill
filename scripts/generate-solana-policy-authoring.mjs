#!/usr/bin/env node
// Canonical implementation lives in bounded-monorepo; never edit the output bundle.
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const monorepo = path.resolve(process.env.BOUNDED_MONOREPO_ROOT || path.join(root, '../bounded-monorepo'))
const require = createRequire(path.join(monorepo, 'packages/cdk/package.json'))
const { build } = require('esbuild')
const output = path.join(root, 'bounded-onchain/scripts/solana-policy.cjs')
const result = await build({
  absWorkingDir: monorepo,
  entryPoints: ['packages/cdk/layers/sol-helper/nodejs/sol-layer/src/raydium-plugin-stuff/authoring-cli.ts'],
  bundle: true, platform: 'node', format: 'cjs', target: 'node22', write: false,
  mainFields: ['module', 'main'],
  minify: true, legalComments: 'inline',
  banner: { js: '// GENERATED by scripts/generate-solana-policy-authoring.mjs. Do not hand-edit.\n// Offline policy authoring only; does not submit transactions.' },
})
const bytes = result.outputFiles[0].contents
if (process.argv.includes('--check')) {
  if (!readFileSync(output).equals(Buffer.from(bytes))) throw new Error('Solana policy authoring bundle is stale')
} else {
  mkdirSync(path.dirname(output), { recursive: true })
  writeFileSync(output, bytes)
}
console.log(`Solana policy authoring bundle: ${bytes.length} bytes`)
